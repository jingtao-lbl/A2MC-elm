if __name__ == "__main__":
    import sys

    if len(sys.argv) < 2:
        print("Usage: python output_parser.py <output_cdl_file>")
        sys.exit(1)

    file_path = sys.argv[1]
    parser = FATESOutputParser(file_path)
    variables = parser.parse()
    dims = parser.get_dimensions()

    print(f"\nParsed {len(variables)} total output variables from {file_path}")

    fates_vars = parser.get_fates_variables()
    elm_vars = parser.get_elm_variables()
    key_elm = parser.get_key_elm_variables()
    print(f"  FATES variables: {len(fates_vars)}")
    print(f"  ELM variables: {len(elm_vars)}")
    print(f"  Key ELM variables found: {len(key_elm)}")

    print(f"\nDimensions:")
    for name, size in sorted(dims.items()):
        print(f"  {name}: {size}")

    print(f"\nVariables by dimension level:")
    by_dim = parser.get_variables_by_dimension()
    for level, vars_list in sorted(by_dim.items()):
        print(f"  {level}: {len(vars_list)} variables")

    print(f"\nVariables by category:")
    by_cat = parser.get_variables_by_category()
    for cat, vars_list in sorted(by_cat.items()):
        print(f"  {cat}: {len(vars_list)} variables")

    print(f"\nSample FATES variables (first 10):")
    for i, (name, var) in enumerate(sorted(fates_vars.items())[:10]):
        print(f"  {var.name} [{var.units}] ({var.dimension_level}) - {var.long_name[:60]}")

    print(f"\nKey ELM variables:")
    for name, var in sorted(key_elm.items()):
        print(f"  {var.name} [{var.units}] ({var.dimension_level}) - {var.long_name[:60]}")
